const LANG_STORE = "kurier.lang";
const LOCALES = { en: "en-GB", ro: "ro-RO" };

function detectLang() {
  try {
    const saved = localStorage.getItem(LANG_STORE);
    if (saved && I18N[saved]) return saved;
  } catch { /* private mode */ }
  const prefs = navigator.languages && navigator.languages.length ? navigator.languages : [navigator.language || "en"];
  return prefs.some((l) => String(l).toLowerCase().startsWith("ro")) ? "ro" : "en";
}

let LANG = detectLang();

function setLang(lang) {
  LANG = I18N[lang] ? lang : "en";
  try { localStorage.setItem(LANG_STORE, LANG); } catch { /* private mode */ }
}

function locale() { return LOCALES[LANG]; }

// t("key", {var}) → text in the current language (English fallback).
function t(key, vars = {}) {
  const entry = I18N[LANG][key] ?? I18N.en[key];
  if (entry === undefined) return key;
  if (typeof entry === "function") return entry(vars);
  return entry.replace(/\{(\w+)\}/g, (_, k) => (vars[k] === undefined ? "" : String(vars[k])));
}

// Static markup: data-i18n → textContent, data-i18n-aria → aria-label.
function applyStatic() {
  document.documentElement.lang = LANG;
  for (const node of document.querySelectorAll("[data-i18n]")) node.textContent = t(node.dataset.i18n);
  for (const node of document.querySelectorAll("[data-i18n-aria]")) {
    node.setAttribute("aria-label", t(node.dataset.i18nAria));
  }
}
