// Romanian: a count ending in 00 or 20–99 takes "de" before the noun
// (7 zile, 30 de zile, 101 zile, 120 de zile). Counts may arrive formatted ("1.234").
function roDe(n) {
  const c = Number(String(n).replace(/\D/g, ""));
  return c > 0 && (c % 100 === 0 || c % 100 >= 20) ? `${n} de` : `${n}`;
}

